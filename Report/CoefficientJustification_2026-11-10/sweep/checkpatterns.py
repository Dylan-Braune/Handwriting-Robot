def Main():
    bad = 0
    for mod,pats in CANDIDATES.items():
        text = patch.SourceOf(mod)
        for p in pats:
            n = text.count(p)
            if n != 1:
                print("%-5s %2d  %s" % ("BAD" if n != 1 else "ok",n,p[:95]))
                bad += 1
    print("\n%d candidate(s) not uniquely addressable out of %d"
          % (bad,sum(len(v) for v in CANDIDATES.values())))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(Main())

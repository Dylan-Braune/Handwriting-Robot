"""Turn the results markdown into one word document with the images inside it.

Reads results/RESULTS.md and results/EXAMPLES.md, writes results/Results.docx
Needs python-docx, which is fine because nothing in here is submitted.

Handles the small subset of markdown those two files use: headings, paragraphs,
pipe tables, `inline code` and ![alt](relative/image.png)
"""
import re
import sys
from pathlib import Path

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Inches, Pt, RGBColor
from PIL import Image

HERE = Path(__file__).resolve().parent
OUT = HERE / "results"
DOCX = OUT / "Results.docx"
PAGE_WIDE = 6.4          # inches of usable width inside the margins
CODE = "Consolas"

try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except Exception:
    pass


def AddRich(par, text):
    """write text into a paragraph, **bold** bold and `code` monospaced"""
    for piece in re.split(r"(\*\*[^*]+\*\*|`[^`]+`)", text):
        if not piece:
            continue
        if piece.startswith("**"):
            par.add_run(piece[2:-2]).bold = True
        elif piece.startswith("`"):
            r = par.add_run(piece[1:-1])
            r.font.name, r.font.size = CODE, Pt(8.5)
        else:
            par.add_run(piece)


def AddTable(doc, rows):
    """rows are the raw pipe lines, the second one is the dashes separator"""
    cells = [[c.strip() for c in r.strip().strip("|").split("|")] for r in rows]
    cells = [c for c in cells if not all(set(x) <= set("-: ") for x in c)]
    if not cells:
        return
    nCol = max(len(c) for c in cells)
    t = doc.add_table(rows=len(cells), cols=nCol)
    t.style = "Table Grid"
    t.autofit = True
    for i, row in enumerate(cells):
        for j in range(nCol):
            cell = t.cell(i, j)
            cell.text = ""
            par = cell.paragraphs[0]
            par.paragraph_format.space_after = Pt(0)
            AddRich(par, row[j] if j < len(row) else "")
            for r in par.runs:
                r.font.size = Pt(8)
                if i == 0:
                    r.bold = True
    doc.add_paragraph().paragraph_format.space_after = Pt(4)


def AddImage(doc, relPath, caption):
    p = (OUT / relPath).resolve()
    if not p.exists():
        doc.add_paragraph("[missing image %s]" % relPath)
        return
    w, h = Image.open(p).size
    # line crops are very wide and short, cap the width and let height follow
    wide = min(PAGE_WIDE, PAGE_WIDE if w >= h else 3.2)
    if h * wide / w > 3.0:                     # keep a tall picture on the page
        wide = 3.0 * w / h
    par = doc.add_paragraph()
    par.alignment = WD_ALIGN_PARAGRAPH.CENTER
    par.add_run().add_picture(str(p), width=Inches(wide))
    if caption:
        cp = doc.add_paragraph()
        cp.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = cp.add_run(caption)
        r.italic, r.font.size = True, Pt(8)
        r.font.color.rgb = RGBColor(0x60, 0x60, 0x60)


IMG_RE = re.compile(r"^!\[(.*?)\]\((.*?)\)\s*$")


def AddMarkdown(doc, path, levelShift=0):
    lines = path.read_text(encoding="utf-8").splitlines()
    i = 0
    while i < len(lines):
        s = lines[i].rstrip()
        if not s.strip():
            i += 1
            continue
        if s.startswith("|"):                  # gather the whole table
            block = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                block.append(lines[i])
                i += 1
            AddTable(doc, block)
            continue
        m = IMG_RE.match(s)
        if m:
            AddImage(doc, m.group(2), m.group(1))
            i += 1
            continue
        if s.startswith("#"):
            n = len(s) - len(s.lstrip("#"))
            doc.add_heading(s[n:].strip(), min(4, n + levelShift))
            i += 1
            continue
        AddRich(doc.add_paragraph(), s)
        i += 1


def Main():
    doc = Document()
    for sec in doc.sections:                   # a little more room for wide tables
        sec.left_margin = sec.right_margin = Inches(0.8)
    st = doc.styles["Normal"]
    st.font.name, st.font.size = "Calibri", Pt(10)

    doc.add_heading("Handwriting robot: full pipeline results", 0)
    p = doc.add_paragraph()
    AddRich(p, "D.R. Braune, 23539195.  Every stage of the pipeline measured "
               "per writer on the existing trained weights, with the example "
               "images the numbers came from.  Generated by "
               "`testing/full_results.py`, `testing/examples.py` and "
               "`testing/makedoc.py`.")

    doc.add_heading("Part A: results per writer", 1)
    AddMarkdown(doc, OUT / "RESULTS.md", levelShift=1)

    doc.add_page_break()
    doc.add_heading("Part B: example images", 1)
    AddMarkdown(doc, OUT / "EXAMPLES.md", levelShift=1)

    doc.save(DOCX)
    print("wrote %s" % DOCX)


if __name__ == "__main__":
    Main()
